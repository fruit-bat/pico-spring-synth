//
// main.c - pico-spring-synth firmware: start up, the two cores, status
// reports.
//
// Core 0: USB (serial console + MIDI), UART MIDI input, status reporting.
//         With SS_DUAL_CORE it also renders part of the strings of every
//         block, in the inter-core FIFO interrupt so that a slow USB print
//         can never hold up the audio.
// Core 1: owns the synth; renders audio blocks into the output DMA ring and
//         applies queued MIDI messages between blocks. The audio DMA
//         interrupt also runs on core 1.
//
// Data flow:
//   UART / USB MIDI --midi_in_poll() on core 0--> SPSC queue (midi_in.c)
//   --apply_midi() on core 1, between blocks--> synth
//   --ss_synth_render*()--> audio buffer --audio_out_submit()--> DMA ring
//   --DMA_IRQ_1--> I2S PIO or PWM
//
// Each audio buffer is AUDIO_OUT_FRAMES = 4 synth blocks. Per block, core 1
// applies MIDI (within a time budget), advances the demo song if one is
// playing, and renders. In dual core mode it asks core 0 for parts
// 1..SS_RENDER_PARTS-1 through the FIFO (CMD_RENDER_PART), renders part 0
// itself, and waits for CMD_PART_DONE before mixing (ss_synth_render_end).
//
// Flash writes (saving settings): flash cannot be read while it is being
// written, so neither core may execute from it. Core 0 sets park_request;
// core 1 finishes its current buffer and spins in RAM (core1_main is RAM
// resident) with core1_parked set; core 0 writes with its interrupts off,
// then clears park_request. The DMA plays out the queued buffers and then
// silence meanwhile, so the audio drops out briefly.
//
// Start up: clocks, USB, MIDI, the synth, saved settings, then core 1
// starts the audio. A demo song (SS_DEMO_MIDI) plays until live MIDI
// arrives; without one a short arpeggio confirms audio.
//
// Once a second core 0 prints a status line with the CPU load per core,
// strings and partials, underruns, MIDI counts, output peak and settings,
// and a second line with the cost per partial.
//
#include <stdio.h>
#include <math.h>
#include "pico/stdlib.h"
#include "pico/multicore.h"
#include "hardware/clocks.h"
#include "hardware/vreg.h"
#include "hardware/irq.h"
#include "hardware/sync.h"
#include "hardware/structs/m33.h"
#include "pico/stdio_usb.h"
#include "tusb.h"

#include "ss_synth.h"
#include "ss_smf.h"
#include "audio_out.h"
#include "midi_in.h"
#include "settings.h"
#if SS_BENCH
#include "bench.h"
#endif

#if SS_AUDIO_OUT_I2S
#define SS_AUDIO_OUT_NAME "I2S"
#else
#define SS_AUDIO_OUT_NAME "PWM"
#endif

// Demo song, generated by CMake (size 0 when SS_DEMO_MIDI is not set)
extern const uint8_t ss_demo_midi[];
extern const size_t ss_demo_midi_size;

static SsSynth synth;       // Large (strings, effects): lives in SRAM
static SsSmf demo;

static volatile bool demo_playing;  // Demo song playing; cleared by core 1 on live MIDI
static volatile bool audio_ok;      // Set by core 1 once the audio output runs
static volatile bool audio_failed;  // Set by core 1 if audio_out_init() failed

// Core 0 asks core 1 to wait in RAM (flash writes): park_request -> parked
static volatile bool park_request;
static volatile bool core1_parked;

// Render statistics for the once-a-second report. Counters are only ever
// incremented, by their one writer, and wrap at 2^32; the report uses the
// change since the previous report.
static volatile uint32_t stat_buffers;      // Audio buffers rendered (core 1)
static volatile uint32_t stat_busy_us;      // Accumulated render time (core 1)
static volatile uint32_t stat_core0_us;     // Time core 0 spent rendering (core 0 FIFO IRQ)
static volatile uint32_t stat_midi_cycles;  // Core 1 cycles applying MIDI
//
// Maxima since the last report are kept by core 1. To read them core 0
// bumps report_request; between buffers core 1 copies them (and the
// synth's output peak) to the report_* variables, clears them and sets
// report_done = report_request. See publish_maxima / collect_maxima.
static volatile uint32_t stat_busy_max_us;  // Worst buffer (core 1)
static volatile uint32_t stat_strings_max;  // Most strings (core 1)
static volatile uint32_t stat_partials_max; // Most partials (core 1)
static volatile uint32_t stat_cost_max;     // Highest render cost (core 1)
// Worst block, in cycles, of: MIDI (and demo), render part 0 (with the
// effects), waiting for core 0's part, the final mix, the whole block
static volatile uint32_t stat_phase_max[5], report_phase_max[5];
static volatile uint32_t report_request;    // Written by core 0
static volatile uint32_t report_done;       // Written by core 1
static volatile uint32_t report_busy_max_us, report_strings_max, report_partials_max, report_cost_max;
static volatile float report_peak;

// Inter-core FIFO commands
#define CMD_RENDER_PART 0x52454e44u  // Core 1 -> core 0: render parts 1..N-1
#define CMD_PART_DONE   0x444f4e45u  // Core 0 -> core 1: done

// ss_smf_advance() callback: pass a message from the demo song to the
// synth (ctx). Core 1, between blocks.
static void on_demo_midi(void *ctx, const uint8_t *msg, uint32_t len) {
    ss_synth_midi((SsSynth *)ctx, msg, len);
}

// MIDI is applied for at most this share of a block; the rest waits for the
// next block. A burst (a big chord arriving over USB all at once) is spread
// over a few blocks instead of causing an audio underrun.
#ifndef SS_MIDI_BUDGET_PERCENT
#define SS_MIDI_BUDGET_PERCENT 15
#endif

static uint32_t midi_budget_cycles;    // SS_MIDI_BUDGET_PERCENT of a block, in CPU cycles

// Pop queued MIDI messages and apply them to the synth until the queue is
// empty or the cycle budget is spent (the check is before each message).
// The first live message stops the demo and resets the synth. Internal
// SysEx codes (midi_in.h) are mapped to synth calls. Core 1, between
// blocks, RAM resident.
static void __not_in_flash_func(apply_midi)(void) {
    MidiMsg m;
    const uint32_t t0 = SS_CYCLE_COUNT();
    while (SS_CYCLE_COUNT() - t0 < midi_budget_cycles && midi_in_pop(&m)) {
        if (demo_playing) {
            demo_playing = false;
            ss_synth_reset(&synth);
        }
        if (m.len == 1 && m.data[0] == MIDI_MSG_RESET) ss_synth_reset(&synth);
        else if (m.len == 3 && m.data[0] == MIDI_MSG_MASTER_VOLUME) {
            ss_synth_set_master_volume(&synth, (uint16_t)(m.data[1] | (m.data[2] << 7)));
        } else if (m.len == 3 && m.data[0] == MIDI_MSG_EQ) {
            ss_synth_set_eq_gs(&synth, m.data[1], m.data[2]);
        } else if (m.len == 2 && m.data[0] == MIDI_MSG_WIDTH) {
            ss_synth_set_width(&synth, m.data[1]);
        } else ss_synth_midi(&synth, m.data, m.len);
    }
}

// Core 1 side of the maxima handover (see above). Between buffers.
static void __not_in_flash_func(publish_maxima)(void) {
    const uint32_t req = report_request;
    if (req == report_done) return;
    report_busy_max_us = stat_busy_max_us;
    report_strings_max = stat_strings_max;
    report_partials_max = stat_partials_max;
    report_cost_max = stat_cost_max;
    for (int i = 0; i < 5; ++i) { report_phase_max[i] = stat_phase_max[i]; stat_phase_max[i] = 0; }
    stat_cost_max = 0;
    report_peak = synth.stats.peak;
    stat_busy_max_us = 0;
    stat_strings_max = 0;
    stat_partials_max = 0;
    synth.stats.peak = 0.0f;
    __dmb(); // Values visible before the acknowledgement
    report_done = req;
}

// Core 0 side: ask core 1 for the maxima and wait for them (at most one
// audio buffer). Returns false on timeout, leaving the previous values.
static bool collect_maxima(void) {
    const uint32_t req = report_request + 1;
    report_request = req;
    const absolute_time_t until = make_timeout_time_ms(50);
    while (report_done != req) {
        if (time_reached(until)) return false;
        tight_loop_contents();
    }
    __dmb();
    return true;
}

// Start this core's cycle counter (SS_CYCLE_COUNT, used for profiling)
static void enable_cycle_counter(void) {
    m33_hw->demcr |= M33_DEMCR_TRCENA_BITS;
    m33_hw->dwt_cyccnt = 0;
    m33_hw->dwt_ctrl |= M33_DWT_CTRL_CYCCNTENA_BITS;
}

// Core 1 entry: start the audio output (so its DMA interrupt runs here),
// then loop forever: get a free buffer, and for each of its blocks apply
// MIDI, advance the demo and render; submit the buffer; update statistics.
// Parks in RAM between buffers when core 0 asks (flash writes). The whole
// loop must stay RAM resident.
static void __not_in_flash_func(core1_main)(void) {
    enable_cycle_counter();
    midi_budget_cycles = (uint32_t)((uint64_t)clock_get_hz(clk_sys) * SS_BLOCK_SIZE / SS_SAMPLE_RATE * SS_MIDI_BUDGET_PERCENT / 100);
    if (!audio_out_init(SS_SAMPLE_RATE)) {
        audio_failed = true;
        for (;;) tight_loop_contents();
    }
    audio_ok = true;

    uint32_t demo_gap = 0; // Blocks of silence between demo repeats
    for (;;) {
        if (park_request) {
            core1_parked = true;
            while (park_request) tight_loop_contents();
            core1_parked = false;
        }
        publish_maxima();
        int16_t *buf = audio_out_acquire();
        const uint32_t t0 = time_us_32();
        for (int b = 0; b < AUDIO_OUT_FRAMES / SS_BLOCK_SIZE; ++b) {
            const uint32_t c0 = SS_CYCLE_COUNT();
            apply_midi();
            stat_midi_cycles = stat_midi_cycles + (SS_CYCLE_COUNT() - c0);
            if (demo_playing) {
                if (demo_gap) {
                    if (--demo_gap == 0) ss_smf_init(&demo, ss_demo_midi, ss_demo_midi_size, SS_SAMPLE_RATE);
                } else if (!ss_smf_advance(&demo, SS_BLOCK_SIZE, on_demo_midi, &synth)) {
                    demo_gap = 3 * SS_SAMPLE_RATE / SS_BLOCK_SIZE; // Restart after 3 s
                }
            }
            int16_t *out = buf + b * SS_BLOCK_SIZE * 2;
#if SS_DUAL_CORE
            const uint32_t c1 = SS_CYCLE_COUNT();
            ss_synth_render_begin(&synth);
            multicore_fifo_push_blocking(CMD_RENDER_PART);
            ss_synth_render_part(&synth, 0);
            const uint32_t c2 = SS_CYCLE_COUNT();
            while (multicore_fifo_pop_blocking() != CMD_PART_DONE) tight_loop_contents();
            const uint32_t c3 = SS_CYCLE_COUNT();
            ss_synth_render_end(&synth, out);
            const uint32_t c4 = SS_CYCLE_COUNT();
            // Worst block of each phase since the last report
            if (c1 - c0 > stat_phase_max[0]) stat_phase_max[0] = c1 - c0;
            if (c2 - c1 > stat_phase_max[1]) stat_phase_max[1] = c2 - c1;
            if (c3 - c2 > stat_phase_max[2]) stat_phase_max[2] = c3 - c2;
            if (c4 - c3 > stat_phase_max[3]) stat_phase_max[3] = c4 - c3;
            if (c4 - c0 > stat_phase_max[4]) stat_phase_max[4] = c4 - c0;
#else
            ss_synth_render(&synth, out);
#endif
            if (ss_synth_active_strings(&synth) > stat_strings_max) stat_strings_max = ss_synth_active_strings(&synth);
            if (ss_synth_active_partials(&synth) > stat_partials_max) stat_partials_max = ss_synth_active_partials(&synth);
            if (ss_synth_cost(&synth) > stat_cost_max) stat_cost_max = ss_synth_cost(&synth);
        }
        const uint32_t dt = time_us_32() - t0;
        audio_out_submit();

        stat_buffers = stat_buffers + 1;
        stat_busy_us = stat_busy_us + dt;
        if (dt > stat_busy_max_us) stat_busy_max_us = dt;
    }
}

#if SS_DUAL_CORE
// Core 0 side of the split render: runs in the FIFO interrupt, so it
// preempts whatever core 0 is doing (USB, printing). Core 1 is
// busy-waiting for the reply, so this has the highest IRQ priority.
static void __not_in_flash_func(core0_fifo_irq)(void) {
    while (multicore_fifo_rvalid()) {
        const uint32_t cmd = multicore_fifo_pop_blocking();
        if (cmd == CMD_RENDER_PART) {
            const uint32_t t0 = time_us_32();
            for (uint32_t p = 1; p < SS_RENDER_PARTS; ++p) ss_synth_render_part(&synth, p);
            stat_core0_us = stat_core0_us + (time_us_32() - t0);
            multicore_fifo_push_blocking(CMD_PART_DONE);
        }
    }
    multicore_fifo_clear_irq();
}
#endif

// Wait ms milliseconds while keeping USB and MIDI input serviced. Core 0.
static void usb_sleep_ms(uint32_t ms) {
    const absolute_time_t until = make_timeout_time_ms(ms);
    while (!time_reached(until)) {
        tud_task();
        midi_in_poll();
    }
}

// Core 0 entry: start up (see the file header), then the main loop: USB
// and MIDI polling, settings commands (with the core 1 park handshake), and
// the status report once a second.
int main(void) {
    if (SS_SYS_CLOCK_KHZ > 150000) {
        // Overclocking: raise the core voltage first
        vreg_set_voltage(VREG_VOLTAGE_1_20);
        sleep_ms(10);
    }
    set_sys_clock_khz(SS_SYS_CLOCK_KHZ, true);

    tusb_init();
    stdio_init_all();
    midi_in_init();

    ss_synth_init(&synth, SS_SAMPLE_RATE);
    const bool settings_loaded = settings_load(&synth);
    if (ss_demo_midi_size && ss_smf_init(&demo, ss_demo_midi, ss_demo_midi_size, SS_SAMPLE_RATE)) {
        demo_playing = true;
    }

    enable_cycle_counter();
#if SS_BENCH
    // Wait (up to 10 s) for the console, so the results are seen
    for (int i = 0; i < 1000 && !stdio_usb_connected(); ++i) usb_sleep_ms(10);
    usb_sleep_ms(500);
    bench_run();
#endif
    multicore_launch_core1(core1_main);
#if SS_DUAL_CORE
    // After the launch handshake, which also uses the FIFO
    irq_set_exclusive_handler(SIO_IRQ_FIFO, core0_fifo_irq);
    irq_set_priority(SIO_IRQ_FIFO, PICO_HIGHEST_IRQ_PRIORITY);
    irq_set_enabled(SIO_IRQ_FIFO, true);
#endif
    while (!audio_ok && !audio_failed) tight_loop_contents();

    if (!demo_playing && audio_ok) {
        // Short arpeggio so there is something to hear at power up
        static const uint8_t keys[] = { 60, 64, 67, 72 };
        for (unsigned i = 0; i < sizeof(keys); ++i) {
            const uint8_t on[3] = { 0x90, keys[i], 100 };
            midi_in_inject(on, 3);
            usb_sleep_ms(120);
        }
        usb_sleep_ms(600);
        const uint8_t off[3] = { 0xb0, 123, 0 }; // All notes off
        midi_in_inject(off, 3);
    }

    const float buffer_us = (float)AUDIO_OUT_FRAMES * 1e6f / audio_out_rate();
    absolute_time_t next_report = make_timeout_time_ms(1000);
    bool info_printed = false;

    for (;;) {
        tud_task();
        midi_in_poll();

        const uint8_t cmd = midi_in_settings_cmd();
        if (cmd) {
            if (!settings_available()) {
                printf("settings: not saved, the firmware reaches the settings sector\n");
            } else {
                // Core 1 stops between blocks (core 0 keeps serving its render
                // requests until then), then flash is ours
                park_request = true;
                while (!core1_parked) tight_loop_contents();
                if (cmd == MIDI_SETTINGS_SAVE) settings_save(&synth);
                else {
                    settings_erase();
                    ss_synth_set_master_volume(&synth, 16383);
                    for (uint8_t p = 0; p < 4; ++p) ss_synth_set_eq_gs(&synth, p, (p & 1) ? 0x40 : 0);
                    ss_synth_set_width(&synth, 100);
                }
                park_request = false;
                printf("settings: %s\n", cmd == MIDI_SETTINGS_SAVE ? "saved to flash" : "erased, defaults restored");
            }
        }

        if (time_reached(next_report)) {
            next_report = make_timeout_time_ms(1000);
            if (!info_printed && stdio_usb_connected()) {
                printf("pico-spring-synth: %lu melodic patches, %lu drum patches\n",
                       (unsigned long)ss_patch_count, (unsigned long)ss_drum_patch_count);
                printf("audio: %s at %.1f Hz, sys clock %lu kHz, %d strings, cost budget %d, block %d, buffer %d frames, %s\n",
                       SS_AUDIO_OUT_NAME, (double)audio_out_rate(),
                       (unsigned long)(clock_get_hz(clk_sys) / 1000), SS_MAX_STRINGS, SS_COST_BUDGET,
                       SS_BLOCK_SIZE, AUDIO_OUT_FRAMES,
                       SS_DUAL_CORE ? "strings on both cores" : "strings on core 1 only");
                printf("settings: %s\n", settings_loaded ? "loaded from flash" : "defaults (none saved)");
                info_printed = true;
            }
            if (audio_failed) {
                printf("audio output failed to start (check pins)\n");
                continue;
            }
            // Counters: change since the last report
            static uint32_t last_buffers, last_busy, last_core0, last_midi_cycles;
            static uint32_t last_part[SS_RENDER_PARTS], last_pblocks[SS_RENDER_PARTS];
            uint32_t now;
            now = stat_buffers;     const uint32_t buffers = now - last_buffers;          last_buffers = now;
            now = stat_busy_us;     const uint32_t busy = now - last_busy;                last_busy = now;
            now = stat_core0_us;    const uint32_t core0 = now - last_core0;              last_core0 = now;
            now = stat_midi_cycles; const uint32_t midi_cycles = now - last_midi_cycles;  last_midi_cycles = now;
            uint32_t part_cyc[SS_RENDER_PARTS], pblocks[SS_RENDER_PARTS];
            for (int p = 0; p < SS_RENDER_PARTS; ++p) {
                now = synth.stats.part_cycles[p];    part_cyc[p] = now - last_part[p];   last_part[p] = now;
                now = synth.stats.partial_blocks[p]; pblocks[p] = now - last_pblocks[p]; last_pblocks[p] = now;
            }
            collect_maxima();
            const uint32_t busy_max = report_busy_max_us;
            const float peak = report_peak;
            // core 1 load includes waiting for core 0's part; it is what
            // limits the synth (100% = no time to spare)
            const float load = buffers ? 100.0f * (float)busy / ((float)buffers * buffer_us) : 0.0f;
            const float load_max = 100.0f * (float)busy_max / buffer_us;
            const float load0 = buffers ? 100.0f * (float)core0 / ((float)buffers * buffer_us) : 0.0f;
            static uint32_t clipped_last;
            const uint32_t clipped = synth.stats.clipped;
            const float peak_db = peak > 1e-6f ? 20.0f * log10f(peak) : -120.0f;
            printf("cpu core1 %5.1f%% (max %5.1f%%) core0 %5.1f%%  strings max %2lu  partials max %3lu  cost max %3lu/%d  underruns %lu  midi %lu (dropped %lu)  peak %4.0f dB  clipped %lu  volume %3.0f%%  eq %+.0f/%+.0f dB  width %u%%%s\n",
                   (double)load, (double)load_max, (double)load0, (unsigned long)report_strings_max,
                   (unsigned long)report_partials_max, (unsigned long)report_cost_max, SS_COST_BUDGET,
                   (unsigned long)audio_out_underruns(),
                   (unsigned long)midi_in_count(), (unsigned long)midi_in_dropped(), (double)peak_db,
                   (unsigned long)(clipped - clipped_last), (double)(100.0f * synth.master_volume),
                   (double)synth.eq.low_db, (double)synth.eq.high_db, (unsigned)synth.width_pct,
                   demo_playing ? "  [demo]" : "");
            clipped_last = clipped;
            // Cost per partial-sample, from the parts other than 0 (part 0
            // also runs the effects): with the string costs, what SS_COST_BUDGET is sized by
            uint32_t pb = 0, pc = 0;
            for (int p = 1; p < SS_RENDER_PARTS; ++p) { pb += pblocks[p]; pc += part_cyc[p]; }
            const float cycles = (float)buffers * buffer_us * (float)clock_get_hz(clk_sys) * 1e-6f;
            {
                const float blk = (float)SS_BLOCK_SIZE * (float)clock_get_hz(clk_sys) / audio_out_rate() * 0.01f;
                printf("    worst block %%: midi %4.1f  part0 %4.1f  wait core0 %4.1f  mix %4.1f  total %5.1f\n",
                       (double)(report_phase_max[0] / blk), (double)(report_phase_max[1] / blk),
                       (double)(report_phase_max[2] / blk), (double)(report_phase_max[3] / blk),
                       (double)(report_phase_max[4] / blk));
            }
            if (pb > 0 && cycles > 0.0f) {
                const float per_partial = (float)pc / ((float)pb * SS_BLOCK_SIZE);
                const float effects = (float)part_cyc[0] - per_partial * (float)pblocks[0] * SS_BLOCK_SIZE;
                printf("    cycles per partial-sample %5.1f  effects %4.1f%%  midi %4.1f%%\n",
                       (double)per_partial, (double)(100.0f * effects / cycles),
                       (double)(100.0f * (float)midi_cycles / cycles));
            }
        }
    }
}
